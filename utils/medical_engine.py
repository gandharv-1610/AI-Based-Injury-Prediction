# ─────────────────────────────────────────────────────────────────────────────
# Risk scoring
# ─────────────────────────────────────────────────────────────────────────────

def _compute_risk_score(
    gait_type: str,
    features: dict,
    bmi: float,
    age: int,
    confidence: float,
) -> int:
    """
    Compute a 0–100 injury risk score combining:
      - Base risk per gait type (clinical severity)
      - Balance asymmetry modifier
      - BMI modifier
      - Age modifier
      - Model confidence (high confidence → score closer to base risk)
    """
    base = _KB.get(gait_type, _KB["normal"])["base_risk"]

    # Balance penalty (0–15 points)
    balance_penalty = min(15, features.get("balance", 0) * 50)

    # BMI modifier (0–10 points; overweight / obese adds risk)
    if bmi >= 30:
        bmi_mod = 10
    elif bmi >= 25:
        bmi_mod = 5
    else:
        bmi_mod = 0

    # Age modifier (0–8 points for older adults)
    if age >= 65:
        age_mod = 8
    elif age >= 45:
        age_mod = 4
    else:
        age_mod = 0

    # Confidence adjuster — uncertain model → pull score towards midpoint (50)
    raw = base + balance_penalty + bmi_mod + age_mod
    adjusted = raw * confidence + 50 * (1 - confidence)

    return int(min(100, max(0, round(adjusted))))


def _risk_category(score: int) -> Tuple[str, str]:
    """Return (category_name, hex_colour)."""
    if score <= 20:
        return "Low",      "#10b981"   # emerald
    elif score <= 45:
        return "Moderate", "#f59e0b"   # amber
    elif score <= 70:
        return "High",     "#ef4444"   # red
    else:
        return "Critical", "#9333ea"   # purple


# ─────────────────────────────────────────────────────────────────────────────
# Public API
# ─────────────────────────────────────────────────────────────────────────────

def generate_report(
    gait_type:  str,
    features:   dict,
    age:        int   = 30,
    weight_kg:  float = 70.0,
    height_cm:  float = 170.0,
    confidence: float = 1.0,
) -> MedicalReport:
    """
    Generate a full clinical medical report.

    Args:
        gait_type   : Predicted class ('normal', 'antalgic', etc.)
        features    : Dict from feature_extractor.extract_features()
        age         : Patient age in years
        weight_kg   : Body weight in kg
        height_cm   : Height in cm
        confidence  : Model confidence [0, 1] for the predicted class

    Returns:
        MedicalReport dataclass
    """
    gait_type = gait_type.lower().strip()
    kb = _KB.get(gait_type, _KB["normal"])

    bmi = weight_kg / ((height_cm / 100) ** 2)
    score = _compute_risk_score(gait_type, features, bmi, age, confidence)
    category, color = _risk_category(score)

    return MedicalReport(
        gait_type          = gait_type,
        injury_risk_score  = score,
        risk_category      = category,
        risk_color         = color,
        primary_condition  = kb["primary_condition"],
        affected_regions   = kb["affected_regions"],
        short_description  = kb["short_description"],
        clinical_insights  = kb["clinical_insights"],
        recommendations    = kb["recommendations"],
        exercises          = kb["exercises"],
        specialist_referral = kb["specialist_referral"],
        follow_up_urgency  = kb["follow_up_urgency"],
        prognosis          = kb["prognosis"],
    )
